"""
create_schema.py — Phase 2.1 schema creation.

Creates all 9 tables in Neon. Idempotent (IF NOT EXISTS throughout).
Reads DATABASE_URL_UNPOOLED from environment only — never from arguments.

Safeguards: S3 (idempotent, dry-run), S8 (credentials from env only).

Usage:
    python create_schema.py --dry-run    # print SQL, no execution
    python create_schema.py              # create tables
    python create_schema.py --verify     # check tables exist
"""

import argparse
import os
import sys
from pathlib import Path

# ── Schema DDL ────────────────────────────────────────────────────────────────
SCHEMA_SQL = """
-- Scraper Premium — Neon PostgreSQL schema
-- Generated by create_schema.py
-- All statements use IF NOT EXISTS — safe to run multiple times (idempotent)

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- jobs must exist before businesses (FK reference)
CREATE TABLE IF NOT EXISTS jobs (
    id                 TEXT        PRIMARY KEY,
    status             TEXT        NOT NULL DEFAULT 'queued',
    config             JSONB       NOT NULL DEFAULT '{}',
    search_query       TEXT,
    category           TEXT,
    country            TEXT,
    state_region       TEXT,
    city               TEXT,
    postal_code        TEXT,
    source             TEXT        NOT NULL DEFAULT 'google_maps',
    start_index        INTEGER     NOT NULL DEFAULT 1,
    end_index          INTEGER     NOT NULL DEFAULT 100,
    daily_limit        INTEGER     NOT NULL DEFAULT 500,
    job_limit          INTEGER     NOT NULL DEFAULT 100,
    records_saved      INTEGER     NOT NULL DEFAULT 0,
    dupes_skipped      INTEGER     NOT NULL DEFAULT 0,
    failed_records     INTEGER     NOT NULL DEFAULT 0,
    retries            INTEGER     NOT NULL DEFAULT 0,
    progress_pct       INTEGER     NOT NULL DEFAULT 0,
    current_index      INTEGER     NOT NULL DEFAULT 0,
    current_business   TEXT,
    last_error         TEXT,
    last_checkpoint_at TIMESTAMPTZ,
    worker_pid         INTEGER,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    started_at         TIMESTAMPTZ,
    finished_at        TIMESTAMPTZ,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_jobs_status     ON jobs(status);
CREATE INDEX IF NOT EXISTS idx_jobs_created_at ON jobs(created_at DESC);

CREATE TABLE IF NOT EXISTS businesses (
    id               TEXT        PRIMARY KEY,
    name             TEXT        NOT NULL,
    category         TEXT,
    phone            TEXT,
    email            TEXT,
    email_guess      TEXT,
    website          TEXT,
    street_address   TEXT,
    city             TEXT,
    state_region     TEXT,
    postal_code      TEXT,
    country          TEXT,
    full_address     TEXT,
    place_id         TEXT        UNIQUE,
    source_url       TEXT,
    source           TEXT        NOT NULL DEFAULT 'google_maps',
    lat              DOUBLE PRECISION,
    lng              DOUBLE PRECISION,
    rating           NUMERIC(3,1),
    review_count     INTEGER,
    price_level      TEXT,
    hours            JSONB,
    photos_count     INTEGER,
    quality_score    INTEGER     NOT NULL DEFAULT 0,
    job_id           TEXT        REFERENCES jobs(id) ON DELETE SET NULL,
    description      TEXT,
    tags             JSONB,
    ai_enriched      BOOLEAN     DEFAULT FALSE,
    change_history   JSONB,
    has_changes      BOOLEAN     DEFAULT FALSE,
    first_seen_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_scraped_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_updated_at  TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_businesses_job_id       ON businesses(job_id);
CREATE INDEX IF NOT EXISTS idx_businesses_city         ON businesses(city);
CREATE INDEX IF NOT EXISTS idx_businesses_country      ON businesses(country);
CREATE INDEX IF NOT EXISTS idx_businesses_quality      ON businesses(quality_score);
CREATE INDEX IF NOT EXISTS idx_businesses_last_scraped ON businesses(last_scraped_at DESC);
CREATE INDEX IF NOT EXISTS idx_businesses_phone        ON businesses(phone) WHERE phone IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_businesses_email        ON businesses(email) WHERE email IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_businesses_fts ON businesses
    USING GIN(to_tsvector('english',
        coalesce(name,'') || ' ' || coalesce(category,'') || ' ' ||
        coalesce(city,'') || ' ' || coalesce(email,'')));

CREATE TABLE IF NOT EXISTS dedup_fingerprints (
    id           BIGSERIAL   PRIMARY KEY,
    tier         TEXT        NOT NULL
                             CHECK(tier IN ('place_id','source_url','phone','domain','name_addr')),
    fingerprint  TEXT        NOT NULL,
    business_id  TEXT        NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(tier, fingerprint)
);
CREATE INDEX IF NOT EXISTS idx_dedup_lookup ON dedup_fingerprints(tier, fingerprint);
CREATE INDEX IF NOT EXISTS idx_dedup_biz    ON dedup_fingerprints(business_id);

CREATE TABLE IF NOT EXISTS activity_logs (
    id           TEXT        PRIMARY KEY DEFAULT gen_random_uuid()::text,
    job_id       TEXT        NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
    event_type   TEXT        NOT NULL,
    message      TEXT        NOT NULL,
    extra        JSONB,
    ts           TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_logs_job_id ON activity_logs(job_id);
CREATE INDEX IF NOT EXISTS idx_logs_ts     ON activity_logs(ts DESC);

CREATE TABLE IF NOT EXISTS checkpoints (
    job_id          TEXT        PRIMARY KEY REFERENCES jobs(id) ON DELETE CASCADE,
    current_index   INTEGER     NOT NULL DEFAULT 0,
    records_saved   INTEGER     NOT NULL DEFAULT 0,
    dupes_skipped   INTEGER     NOT NULL DEFAULT 0,
    processed_urls  JSONB       NOT NULL DEFAULT '[]',
    checkpoint_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS quotas (
    date_key    DATE        PRIMARY KEY,
    used        INTEGER     NOT NULL DEFAULT 0,
    lim         INTEGER     NOT NULL DEFAULT 500,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS settings (
    key         TEXT        PRIMARY KEY,
    value       TEXT,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS schedules (
    id          TEXT        PRIMARY KEY DEFAULT gen_random_uuid()::text,
    name        TEXT        NOT NULL,
    config      JSONB       NOT NULL DEFAULT '{}',
    cron        TEXT        NOT NULL DEFAULT '0 6 * * *',
    enabled     BOOLEAN     NOT NULL DEFAULT TRUE,
    next_run    TIMESTAMPTZ,
    last_run    TIMESTAMPTZ,
    run_count   INTEGER     NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS migration_runs (
    id           BIGSERIAL   PRIMARY KEY,
    run_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    phase        TEXT        NOT NULL,
    status       TEXT        NOT NULL,
    json_backup  TEXT,
    counts_json  JSONB,
    notes        TEXT
);
"""

EXPECTED_TABLES = [
    "jobs", "businesses", "dedup_fingerprints", "activity_logs",
    "checkpoints", "quotas", "settings", "schedules", "migration_runs",
]


def get_db_url() -> str | None:
    """Read DATABASE_URL_UNPOOLED from environment only. Never from arguments. (S8)"""
    url = os.environ.get("DATABASE_URL_UNPOOLED") or os.environ.get("DATABASE_URL")
    return url or None


def run_schema(dry_run: bool = False, verify_only: bool = False) -> bool:
    db_url = get_db_url()

    if not db_url:
        print("⚠️  DATABASE_URL_UNPOOLED not set — skipping live database operations.")
        print("   Set DATABASE_URL_UNPOOLED in .env to run against Neon.")
        if dry_run:
            print("\n=== DRY RUN SQL (would be executed) ===")
            print(SCHEMA_SQL)
        return True  # Not a failure — just no DB configured

    try:
        import psycopg2
    except ImportError:
        print("❌ psycopg2 not installed. Run: pip install psycopg2-binary==2.9.9")
        return False

    if dry_run:
        print("=== DRY RUN — SQL that would be executed ===")
        print(SCHEMA_SQL)
        print("=== End of dry run. No changes made. ===")
        return True

    if verify_only:
        try:
            conn = psycopg2.connect(db_url)
            cur = conn.cursor()
            cur.execute("""
                SELECT table_name FROM information_schema.tables
                WHERE table_schema = 'public'
            """)
            existing = {row[0] for row in cur.fetchall()}
            conn.close()
            print("=== Table Verification ===")
            all_ok = True
            for t in EXPECTED_TABLES:
                found = t in existing
                print(f"  {'✅' if found else '❌'} {t}")
                if not found:
                    all_ok = False
            return all_ok
        except Exception as e:
            print(f"❌ Verification failed: {e}")
            return False

    # Actual schema creation — wrapped in a single transaction
    try:
        conn = psycopg2.connect(db_url)
        conn.autocommit = False
        cur = conn.cursor()
        print("Creating schema in Neon...")
        cur.execute(SCHEMA_SQL)
        # Record in migration_runs
        cur.execute(
            "INSERT INTO migration_runs (phase, status, notes) VALUES (%s, %s, %s)",
            ("schema", "completed", "Schema created via create_schema.py")
        )
        conn.commit()
        conn.close()
        print("✅ Schema created successfully.")
        # Verify
        return run_schema(verify_only=True)
    except Exception as e:
        if "conn" in dir():
            conn.rollback()
            conn.close()
        print(f"❌ Schema creation failed (rolled back): {e}")
        return False


def main():
    # Load .env manually — never reads secrets as arguments (S8)
    env_path = Path(__file__).resolve().parent.parent.parent / ".env"
    if env_path.exists():
        for line in env_path.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, val = line.split("=", 1)
            if key.strip() not in os.environ:
                os.environ[key.strip()] = val.strip()

    parser = argparse.ArgumentParser(description="Create Neon schema for Scraper Premium")
    parser.add_argument("--dry-run",     action="store_true", help="Print SQL without executing")
    parser.add_argument("--verify",      action="store_true", help="Check tables exist")
    args = parser.parse_args()

    ok = run_schema(dry_run=args.dry_run, verify_only=args.verify)
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
